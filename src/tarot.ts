/** 洗牌：78 张打乱，每张各自决定正逆位。用系统给的真随机数 */
export function shuffle(withRev:boolean):Drawn[]{
  const n=TOTAL,buf=new Uint32Array(n*2);
  try{crypto.getRandomValues(buf);}catch{for(let i=0;i<buf.length;i++)buf[i]=Math.floor(Math.random()*2**32);}
  const deck=Array.from({length:n},(_,c)=>c);
  for(let i=n-1;i>0;i--){const j=buf[i]%(i+1);[deck[i],deck[j]]=[deck[j],deck[i]];}
  return deck.map((c,i)=>({c,...(withRev&&buf[n+i]%2===1?{r:true}:{})}));
}

