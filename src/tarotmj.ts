/* 元素：不是牌义，是这张牌「以什么方式在动」。几张连着读，看它怎么流 */
const flowWord=['起了念头、想行动','动了感情','在想、在说','落到实处'];
/** 三张以上、元素有变化时，顺着说一遍 */
export function flowOf(ds:Drawn[]):string{
  const ks=ds.map(d=>suitOf(d.c));
  if(ds.length<3||ks.some(k=>k<0)||new Set(ks).size<2)return '';
  const out:string[]=[];ks.forEach(k=>{if(out[out.length-1]!==flowWord[k])out.push(flowWord[k]);});
  return '顺着读：先是'+out.join('，再')+'。';
}

